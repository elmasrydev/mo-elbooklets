const base = (args && args.base) || 'main'
const head = (args && args.head) || 'HEAD'
const scopeNote = (args && args.scopeNote) || ''
const changedFiles = (args && args.changedFiles) || []

// Path-based dimension gating. With no file list every dimension runs — a
// missed dimension is worse than a wasted one.
const touches = (re) => !changedFiles.length || changedFiles.some((f) => re.test(f))

const hasGraphql = touches(/\.graphql$|src\/generated\/|apollo|Document|useQuery|useMutation/i)
const hasAuth = touches(/auth|otp|login|register|password|session|token|secure-store/i)
const hasQuiz = touches(/quiz|question|answer|score|match|paragraph/i)
const hasUi = touches(/\.tsx$|locales\/|i18n|config\/(colors|fonts|spacing|layout)/i)
const hasTests = touches(/__tests__|\.test\.|\.spec\.|jest|e2e\//i)

