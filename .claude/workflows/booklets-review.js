const DIMENSIONS = ALL_DIMENSIONS.filter((d) => d.applies)
const skipped = ALL_DIMENSIONS.filter((d) => !d.applies).map((d) => d.key)

log(`Reviewing ${base}...${head} across ${DIMENSIONS.length} dimensions at max effort`)
if (skipped.length) log(`Skipped (no matching files changed): ${skipped.join(', ')}`)
if (!changedFiles.length) log('No changedFiles passed — every dimension ran unfiltered')

// --- Review -> verify, pipelined (no barrier between stages) ---------------

const reviewed = await pipeline(
  DIMENSIONS,
  (d) =>
    agent(`${CONTEXT}\n\n${RULES}\n\n--- YOUR DIMENSION: ${d.key} ---\n${d.prompt}`, {
      label: `review:${d.key}`,
      phase: 'Review',
      effort: d.effort || 'max',
      schema: FINDINGS_SCHEMA,
    }),
  (result, d) => {
    const found = (result && result.findings) || []
    if (!found.length) return []
    // Cap the verification fan-out per dimension so a noisy reviewer cannot
    // blow the agent budget; verify the most severe first.
    const RANK = { blocker: 0, high: 1, medium: 2, low: 3 }
    const ordered = found
      .slice()
      .sort((a, b) => (RANK[a.severity] === undefined ? 9 : RANK[a.severity]) - (RANK[b.severity] === undefined ? 9 : RANK[b.severity]))
    const MAX_VERIFY = 6
    const toVerify = ordered.slice(0, MAX_VERIFY)
    if (ordered.length > MAX_VERIFY) {
      log(`${d.key}: ${ordered.length} findings, verifying the ${MAX_VERIFY} most severe — ${ordered.length - MAX_VERIFY} deferred unverified`)
    }
    return parallel(
      toVerify.map((f) => () =>
        parallel(
          ['does-it-reproduce', 'is-the-rule-real', 'is-it-already-handled'].map((lens) => () =>
            agent(
              `${CONTEXT}\n\n${RULES}\n\nA reviewer claims this defect exists. Your job is to REFUTE it.\n\n` +
                `File: ${f.file}:${f.line}\nCategory: ${f.category}\nSeverity: ${f.severity}\n` +
                `Claim: ${f.summary}\nFailure scenario: ${f.failure_scenario}\nEvidence given: ${f.evidence}\n\n` +
                `Refute it through the "${lens}" lens:\n` +
                `- does-it-reproduce: read the real code and try to construct the failing input. If the ` +
                `scenario cannot actually occur, it is refuted.\n` +
                `- is-the-rule-real: verify the rule it invokes against CLAUDE.md, mobile-otp-guide.md, or ` +
                `the actual config/token files. A misremembered or non-existent rule refutes the finding.\n` +
                `- is-it-already-handled: look for a guard, wrapper, link in src/lib/apollo.ts, shared util, ` +
                `navigator branch, or existing test elsewhere in the repo that already prevents this.\n\n` +
                `Read the actual files — do not judge from the snippet. Default to refuted=true when you ` +
                `are uncertain. A finding that wastes the fixer's time is worse than a missed one.`,
              { label: `verify:${d.key}:${f.file}`, phase: 'Verify', effort: 'max', schema: VERDICT_SCHEMA }
            )
          )
        ).then((votes) => {
          const cast = votes.filter(Boolean)
          const kept = cast.filter((v) => !v.refuted)
          const severities = kept.map((v) => v.corrected_severity).filter((s) => s && s !== 'none')
          return {
            finding: f,
            dimension: d.key,
            survived: kept.length >= 2,
            votes: cast.length,
            upheld: kept.length,
            refutations: cast.filter((v) => v.refuted).map((v) => v.reason),
            severity: severities.length ? severities[0] : f.severity,
          }
        })
      )
    )
  }
)

const judged = reviewed.filter(Boolean).flat().filter(Boolean)
const confirmed = judged.filter((j) => j.survived)
const dropped = judged.filter((j) => !j.survived)

log(`${judged.length} verified findings -> ${confirmed.length} confirmed, ${dropped.length} refuted`)

// --- Completeness critic ---------------------------------------------------

phase('Synthesize')

const RANK = { blocker: 0, high: 1, medium: 2, low: 3 }
const ranked = confirmed
  .map((c) => Object.assign({}, c.finding, { severity: c.severity, dimension: c.dimension, upheld: c.upheld, votes: c.votes }))
  .sort((a, b) => (RANK[a.severity] === undefined ? 9 : RANK[a.severity]) - (RANK[b.severity] === undefined ? 9 : RANK[b.severity]))

const critic = await agent(
  `${CONTEXT}\n\n${RULES}\n\n` +
    `A review of this diff ran across these dimensions: ${DIMENSIONS.map((d) => d.key).join(', ')}.\n` +
    (skipped.length ? `These were skipped as inapplicable: ${skipped.join(', ')}.\n` : '') +
    `It confirmed ${ranked.length} findings:\n` +
    (ranked.length ? ranked.map((f) => `- [${f.severity}] ${f.file}:${f.line} — ${f.summary}`).join('\n') : '(none)') +
    `\n\nYou are the completeness critic. Do not re-review what was covered. Answer only:\n` +
    `1. Which changed file, function, or behaviour did NO dimension actually examine?\n` +
    `2. Which of the burned-before rules above is relevant to this diff but was not checked?\n` +
    `3. Is there a defect class this diff invites that none of the dimension prompts name?\n` +
    `4. Was a dimension skipped that the changed files actually needed?\n\n` +
    `If you find a concrete defect while answering, report it as a finding with the same fields ` +
    `the reviewers used. Otherwise return an empty findings array and say what is uncovered in ` +
    `the gaps field.`,
  {
    label: 'completeness-critic',
    phase: 'Synthesize',
    effort: 'max',
    schema: {
      type: 'object',
      properties: {
        gaps: { type: 'array', items: { type: 'string' } },
        findings: FINDINGS_SCHEMA.properties.findings,
      },
      required: ['gaps', 'findings'],
    },
  }
)

return {
  scope: { base, head, changedFiles: changedFiles.length },
  dimensions: DIMENSIONS.map((d) => d.key),
  skipped_dimensions: skipped,
  confirmed: ranked,
  unverified_from_critic: (critic && critic.findings) || [],
  coverage_gaps: (critic && critic.gaps) || [],
  refuted: dropped.map((d) => ({
    file: d.finding.file,
    line: d.finding.line,
    summary: d.finding.summary,
    upheld: d.upheld,
    votes: d.votes,
    why_refuted: d.refutations,
  })),
  note: 'confirmed = survived >=2 of 3 refutation votes. unverified_from_critic did NOT go through the panel — verify before acting on it.',
}
