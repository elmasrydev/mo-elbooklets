const RULES = `
Rules this codebase has actually been burned by:
- Debug gate: the OTP skip and every debug affordance is gated by isDebugMode() reading
  app.json > extra.debugMode ONLY. Widening it (__DEV__, emulator detection, an env var) is
  a merge blocker — a prod build must never show OTP skip.
- GraphQL discipline: every operation lives in a domain .graphql file under src/graphql/ and
  is consumed as a generated typed document. No inline gql tags or query strings in screens.
  src/generated/* and schema.graphql are never hand-edited (npm run codegen / schema:pull own
  them).
- Partial responses: the client runs errorPolicy: 'all', so a response can carry data AND
  field-level errors. Gate error states with loadFailureMessage() (src/utils/queryError.ts) —
  only a response with NO data is a load failure. Never blank a screen that has something to
  render.
- OTP contract (mobile-otp-guide.md): codes are scoped to purpose+audience so every flow
  starts with a fresh send; resend locked 60s after EVERY send including the automatic one;
  countdown from expires_in, never hardcoded; send success:false means rate-limited — show the
  server message, never auto-retry; send success:true says nothing about the account existing,
  so always advance to the code screen (anti-enumeration); after a successful password reset
  every token is revoked — clear the token and route to login, never auto-login.
- Arabic-Indic digits: never strip with an ASCII-only \\d / [^0-9] before normalizing — it
  silently deletes an Arabic code. normalizeDigits (src/utils/digits.ts) runs first.
- Quiz invariants: Question.type is one of six values — branch on type via the guards in
  src/utils/quizQuestionTypes.ts, never on answers.length. Scoring is unit-based (match = one
  per pair, paragraph = sum of children); xp is server-derived, never computed client-side.
  Submit is exactly one entry per TOP-LEVEL question via buildSubmitPayload. Results
  userAnswers is flat — regroup with groupUserAnswers; answer_1 is null for match/paragraph.
- i18n: no hardcoded user-facing strings — everything through t(), key added to BOTH
  src/i18n/locales/en.json and ar.json. The root /locales directory is stale; editing it is a
  finding.
- RTL: textAlign: 'left' and let native RTL flip it — EXCEPT TextInput, which uses
  INPUT_TEXT_ALIGN from src/lib/rtl.ts and must not also set textAlign in its style.
- Fonts: font follows the text's script, not the UI language — pass isArabicText(str) as
  forceArabic for user-supplied text. Never a bare fontWeight (drops the custom family on
  Android — use typography(style, weight) / fontWeight(weight)).
- Design tokens from src/config/ (colors, spacing, layout, fonts) — no hardcoded values.
- testIDs: kebab-case {screen}-{element} on every new interactive element.
- Regex on Hermes: explicit \\uXXXX ranges, never \\p{L} — an unsupported property escape is a
  bundle-load parse error. In an assembled character class the hyphen stays last.
- validators.ts is the single source of truth for name/password/mobile policy (registration
  password = min 8 chars). Never re-inline a copy.
- TypeScript strict: no any without a comment explaining why. Functional components only,
  StyleSheet.create() for styles. No Redux, NativeWind, or class components.
`.trim()

const FINDINGS_SCHEMA = {
  type: 'object',
  properties: {
    findings: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          file: { type: 'string', description: 'repo-relative path' },
          line: { type: 'integer', description: '1-indexed line the defect anchors to' },
          category: { type: 'string', description: 'kebab-case slug, e.g. debug-gate-widening' },
          severity: { type: 'string', enum: ['blocker', 'high', 'medium', 'low'] },
          summary: { type: 'string', description: 'one sentence stating the defect' },
          failure_scenario: { type: 'string', description: 'concrete inputs/state -> wrong output, crash, or exposure' },
          evidence: { type: 'string', description: 'the code that proves it, plus any CLAUDE.md / guide reference' },
        },
        required: ['file', 'line', 'category', 'severity', 'summary', 'failure_scenario', 'evidence'],
      },
    },
  },
  required: ['findings'],
}

const VERDICT_SCHEMA = {
  type: 'object',
  properties: {
    refuted: { type: 'boolean', description: 'true if the finding does not hold' },
    reason: { type: 'string' },
    corrected_severity: { type: 'string', enum: ['blocker', 'high', 'medium', 'low', 'none'] },
  },
  required: ['refuted', 'reason', 'corrected_severity'],
}

