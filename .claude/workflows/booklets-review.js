// ---------------------------------------------------------------------------
// args: { base, head, scopeNote, changedFiles }
//   base         — ref to diff against ("main", or "HEAD" for the working tree)
//   head         — "HEAD"; uncommitted changes are always included
//   changedFiles — array of repo-relative paths; gates which dimensions run
